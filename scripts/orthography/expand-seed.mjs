const entries = [];
let counter = 1;

for (const [ruleId, words] of Object.entries(groups)) {
  for (const word of words) {
    const clean = String(word).trim().toLowerCase();
    if (!clean) continue;
    entries.push({
      id: `o${String(counter).padStart(3, '0')}`,
      lemma: clean,
      correct: clean,
      ruleTags: [ruleId],
      difficulty: difficultyByRule[ruleId],
      flags: { dictionaryWord: false },
    });
    counter += 1;
  }
}

const uniqueByWord = new Map();
for (const entry of entries) {
  if (!uniqueByWord.has(entry.correct)) uniqueByWord.set(entry.correct, entry);
}

const finalEntries = Array.from(uniqueByWord.values());
const out = path.resolve('scripts/orthography/seed-lexicon.json');
fs.writeFileSync(out, `${JSON.stringify(finalEntries, null, 2)}\n`, 'utf8');
console.log(`seed entries: ${finalEntries.length}`);